const {parseHTML,DOMParser}=require('linkedom');
const root=__dirname;
const {document,NodeFilter}=parseHTML('<html><body></body></html>');
Object.defineProperty(document,'baseURI',{value:'https://baekgujuju.github.io/Archive/v2/'});
